// Checks that the browser crypto (onion-client.js) matches the Python code.
// Run by tests/test_chat.py: node tests/js/interop.mjs input.json
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const client = require("../../web/static/js/onion-client.js");
const input = JSON.parse(readFileSync(process.argv[2], "utf8"));

// 1. Browser -> Python: build a padded chat onion for Python to peel.
const packet = await client.buildChatOnion({
  text: input.text,
  from: { user_id: "u-node", name: "Node tester" },
  to: input.recipient,
  relays: input.relays,
  mailboxId: input.mailbox_id,
  cellBytes: input.cell_bytes,
});

// 2. Python -> Browser: decrypt an end-to-end envelope made by Python.
const der = Buffer.from(
  input.python_private_pkcs8_pem.replace(/-----(BEGIN|END) PRIVATE KEY-----/g, "").replace(/\s+/g, ""),
  "base64"
);
const privateKey = await globalThis.crypto.subtle.importKey(
  "pkcs8", der, { name: "RSA-OAEP", hash: "SHA-256" }, false, ["decrypt"]
);
const decrypted = await client.decryptE2E(input.python_e2e, privateKey);

// 3. A key generated by the browser code has an exportable public key.
const identity = await client.generateIdentity();

console.log(JSON.stringify({
  packet,
  packet_bytes: client.canonicalJson(packet).length,
  decrypted,
  identity_pem_ok: identity.publicKeyPem.startsWith("-----BEGIN PUBLIC KEY-----"),
}));
